/** Helper: busca un estado por su clave INEGI */
export function getEstadoById(id: string): Estado | undefined {
  return MEXICO.estados.find(e => e.id === id);
}

/** Helper: busca un estado por su nombre */
export function getEstadoByNombre(nombre: string): Estado | undefined {
  return MEXICO.estados.find(e => e.nombre.toLowerCase() === nombre.toLowerCase());
}

/** Helper: busca un municipio por nombre dentro de un estado */
export function getMunicipioByNombre(estadoId: string, nombre: string) {
  const estado = getEstadoById(estadoId);
  return estado?.municipios.find(m => m.nombre.toLowerCase() === nombre.toLowerCase());
}
